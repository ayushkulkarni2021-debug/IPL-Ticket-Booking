-- Row Level Security (needed because the browser uses the publishable key)
alter table public.matches  enable row level security;
alter table public.bookings enable row level security;

create policy "Anyone can read matches"    on public.matches  for select using (true);
create policy "Anyone can update seats"    on public.matches  for update using (true) with check (available_seats >= 0);
create policy "Anyone can create bookings" on public.bookings for insert with check (true);
create policy "Anyone can read bookings"   on public.bookings for select using (true);

-- Realtime: broadcast changes on both tables
alter publication supabase_realtime add table public.matches;
alter publication supabase_realtime add table public.bookings;
